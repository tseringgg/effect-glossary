#!/usr/bin/env python3
"""Evaluate the rules of corrections/hand_groups.json over every in-scope card. NEW FILES ONLY: build/hand_group_hits.json, reports/hand-groups.md.

    python src/build_hand_groups.py        # seconds; run after build_keyword_facet.py (keyword rules read the facet), before build_manual_layer.py and build_manual_suggestions.py

A hit is a SUGGESTION: it never places a card, never changes a group, a count or any of the six figures. HAND_GROUPS = False writes nothing and removes both files. A rule that is invalid stops the build with
the reason (never silently skipped).
"""
import collections
import io
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hand_groups as H

HAND_GROUPS = True
HERE = H.HERE
BUILD = os.path.join(HERE, "build")
OUT = os.path.join(BUILD, "hand_group_hits.json")
OUT_MD = os.path.join(HERE, "reports", "hand-groups.md")


def jl(n):
    with io.open(os.path.join(BUILD, n), encoding="utf-8") as fh:
        return json.load(fh)


def words(r):
    if r["type"] == "text":
        s = "the card text has a sentence with " + " or ".join("“%s”" % x for x in r["any"])
        return s + ((", unless that sentence also has " + " or ".join("“%s”" % x for x in r["not"])) if r.get("not") else "")
    if r["type"] == "keyword":
        return "the card carries the keyword %s" % r["keyword"]
    return "the card carries the community tag %s" % r["tag"]


def main():
    if not HAND_GROUPS:
        for p in (OUT, OUT_MD):
            if os.path.exists(p):
                os.remove(p)
        print("HAND_GROUPS is off: nothing written")
        return
    doc = H.load()                                   # raises with every problem listed
    cards = jl("ability_taxonomy_cards.json")["cards"]
    texts = {o: c["t"] or "" for o, c in cards.items()}
    keywords, tags = {}, {}
    need_kw = any(r["type"] == "keyword" for g in doc["groups"].values() for r in g.get("rules", []))
    need_tag = any(r["type"] == "tag" for g in doc["groups"].values() for r in g.get("rules", []))
    if need_kw:
        if not os.path.exists(os.path.join(BUILD, "keyword_facet.json")):
            raise SystemExit("a keyword rule needs build/keyword_facet.json: run python src/build_keyword_facet.py first")
        keywords = {n: set(v["c"]) for n, v in jl("keyword_facet.json")["keywords"].items()}
    if need_tag:
        scope = set(texts)
        for t in json.load(io.open(os.path.join(HERE, "data", "oracle-tags-20261014.json"), encoding="utf-8")):
            if t.get("type") == "oracle":
                tags[t["slug"]] = {g["oracle_id"] for g in t["taggings"] if g["oracle_id"] in scope}
    ev = H.evaluate(doc, texts, keywords, tags)
    groups = {}
    for slug, g in sorted(doc["groups"].items()):
        hits = {} if g.get("retired") else ev[slug]["hits"]
        groups[slug] = {"name": g["name"], "note": g.get("note", ""), "created": g.get("created", ""), "retired": bool(g.get("retired")),
                        "rules": [{"id": r["id"], "type": r["type"], "confidence": r.get("confidence", 0.6), "words": words(r)} for r in g.get("rules", [])],
                        "cards": len(hits), "hits": {o: hits[o] for o in sorted(hits)}}
    out = {"v": 1, "label": "Hand-defined group: its rules only suggest cards; a member is a person's Add click.", "groups": groups}
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(out, ensure_ascii=False, sort_keys=True, separators=(",", ":")))
    L = ["# Hand-defined groups", "", "Generated by `src/build_hand_groups.py` from `corrections/hand_groups.json`. Do not edit. A rule match is a suggestion, never a placement.", ""]
    for slug, g in groups.items():
        L += ["## hand:%s — %s%s" % (slug, g["name"], " (retired)" if g["retired"] else ""), "", g["note"], "", "| rule | what it matches | cards |", "|---|---|---:|"]
        per = collections.Counter(r[0] for h in g["hits"].values() for r in h)
        L += ["| %s | %s | %d |" % (r["id"], r["words"].replace("|", "/"), per.get(r["id"], 0)) for r in g["rules"]] + ["", "Cards matched by at least one rule: **%d**." % g["cards"], ""]
    with io.open(OUT_MD, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L))
    print({s: g["cards"] for s, g in groups.items()})


if __name__ == "__main__":
    main()
